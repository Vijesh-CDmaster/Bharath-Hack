/** Compact box-drawing tree for README structure sections. */
function treeText(paths: string[]): string {
  type Node = { name: string; children: Map<string, Node> };
  const root: Node = { name: ".", children: new Map() };
  for (const p of paths) {
    let node = root;
    for (const seg of p.split("/")) {
      if (!node.children.has(seg)) node.children.set(seg, { name: seg, children: new Map() });
      node = node.children.get(seg)!;
    }
  }
  const lines: string[] = [];
  const walk = (node: Node, prefix: string) => {
    const entries = [...node.children.values()].sort((a, b) => {
      const aDir = a.children.size > 0, bDir = b.children.size > 0;
      return aDir === bDir ? a.name.localeCompare(b.name) : aDir ? -1 : 1;
    });
    entries.forEach((child, i) => {
      const last = i === entries.length - 1;
      lines.push(`${prefix}${last ? "└── " : "├── "}${child.name}${child.children.size > 0 ? "/" : ""}`);
      if (child.children.size > 0) walk(child, `${prefix}${last ? "    " : "│   "}`);
    });
  };
  walk(root, "");
  return lines.slice(0, 80).join("\n") || "(no files yet)";
}

// ---------- 2. Guaranteed preview entry for web projects ----------

export async function ensurePreviewEntry(orgId: string, session: PipelineSession): Promise<void> {
  const platform = (session.targetPlatform ?? "web").toLowerCase();

  const files = session.workspaceFiles ?? [];
  if (files.length === 0) return;
  if (files.some((f) => f.path.toLowerCase().endsWith(".html"))) return; // already previewable

  const model =
    session.executions.find((e) => e.status === "verified" || e.status === "flagged")?.servedBy ??
    session.executions.find((e) => e.model)?.model ??
    "openai/gpt-oss-20b";

  try {
    const { output, servedBy } = await geminiAdapters.generatePreviewEntry({
      projectTitle: session.workflow?.title ?? "Generated Project",
      summary: session.workflow?.summary ?? "",
      stack: stackTextOf(session),
      platform,
      files: files.slice(0, 40).map((f) => ({
        path: f.path,
        excerpt: f.path.toLowerCase().endsWith(".html") ? f.content.slice(0, 300) : "",
      })),
      model,
    });

    const ops = extractFileOps(output);
    const applied: string[] = [];
    for (const op of ops) {
      // Only entry-page artifacts may be created by this pass.
      if (!/\.(html?|css|js)$/i.test(op.path)) continue;
      const res = applyFileOpToSession(session, op, { taskId: PREVIEW_TASK_ID, model: servedBy ?? model });
      if (res.ok) applied.push(res.op.path);
    }

    await recordToLedger({
      orgId,
      sessionId: session.id,
      gate: "execution",
      eventType: applied.length > 0 ? "preview_entry_generated" : "preview_entry_failed",
      actor: "ai",
      model: servedBy ?? model,
      detail: {
        summary:
          applied.length > 0
            ? `Preview entry generated for the web project: ${applied.join(", ")}`
            : "Preview entry generation produced no usable files — workspace preview falls back to the file inventory.",
        files: applied,
      },
    }).catch(() => undefined);
  } catch (err) {
    await recordToLedger({
      orgId,
      sessionId: session.id,
      gate: "execution",
      eventType: "preview_entry_failed",
      actor: "system",
      detail: {
        summary: `Preview entry generation failed: ${err instanceof Error ? err.message : "unknown error"}`,
      },
    }).catch(() => undefined);
  }
}
